// Refreshes the public suffixes address patterns are checked against
// (packages/server/src/public-suffixes.ts) from the Public Suffix List,
// including its private section, where shared hosts such as vercel.app and
// github.io are listed. Run before each release, and commit the result:
//
//   bun scripts/update-public-suffixes.ts [path to a downloaded public_suffix_list.dat]
//
// Only rules of two or more labels are kept: a pattern's fixed part always has
// at least two (`*.com` is refused without the list), so the one-label rules,
// about a seventh of the list, are never needed. Names are stored in their
// `xn--` form, as hosts are compared after the URL parser has converted them.
//
// Shared hosts the list misses are kept by hand in
// packages/server/src/public-suffix-supplement.ts, which this leaves alone; it
// names any of them the list has since added, so they can be removed there.
import { domainToASCII } from "node:url";
import { join } from "node:path";
import { PUBLIC_SUFFIX_SUPPLEMENT } from "../packages/server/src/public-suffix-supplement.ts";

const SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUT = join(import.meta.dir, "../packages/server/src/public-suffixes.ts");

/** The list's multi-label rules, grouped by their last label: `tld:rest,rest;…`, each rest with its own `*.` or `!`. */
export function compactRules(list: string): { version: string; rules: string; count: number } {
  const version = /^\/\/ VERSION: (\S+)/m.exec(list)?.[1];
  if (version === undefined) throw new Error("This doesn't look like the Public Suffix List: it names no VERSION.");
  const byLast = new Map<string, Set<string>>();
  let count = 0;
  for (const line of list.split("\n")) {
    const rule = line.trim().split(/\s/)[0]!;
    if (rule === "" || rule.startsWith("//") || !rule.includes(".")) continue;
    const prefix = rule.startsWith("!") ? "!" : rule.startsWith("*.") ? "*." : "";
    const name = domainToASCII(rule.slice(prefix.length));
    if (name === "") throw new Error(`Can't read the rule ${JSON.stringify(rule)}.`);
    const labels = name.split(".");
    const last = labels.pop()!;
    const rest = `${prefix}${labels.join(".")}`;
    if (/[,;:]/.test(rest + last)) throw new Error(`The rule ${JSON.stringify(rule)} has a character the compact form uses.`);
    if (!byLast.has(last)) byLast.set(last, new Set());
    byLast.get(last)!.add(rest);
    count++;
  }
  const rules = [...byLast.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([last, rests]) => `${last}:${[...rests].sort().join(",")}`)
    .join(";");
  return { version, rules, count };
}

/** The supplement's hosts this list now has as its own rules, which can be removed from the supplement. */
export function supplementNowListed(list: string): string[] {
  const rules = new Set(list.split("\n").map((line) => line.trim().split(/\s/)[0]!).filter((rule) => rule !== "" && !rule.startsWith("//")).map((rule) => domainToASCII(rule)));
  return PUBLIC_SUFFIX_SUPPLEMENT.map((entry) => entry.suffix).filter((suffix) => rules.has(suffix));
}

if (import.meta.main) {
  const given = process.argv[2];
  const list = given === undefined ? await (await fetch(SOURCE)).text() : await Bun.file(given).text();
  const { version, rules, count } = compactRules(list);
  await Bun.write(
    OUT,
    `// Generated by scripts/update-public-suffixes.ts from the Public Suffix List
// (${SOURCE}), version ${version}: its ${count} rules of two or more
// labels, ICANN and private sections, grouped by last label. Don't edit by hand.
//
// The list's data is subject to the terms of the Mozilla Public License, v. 2.0.
// If a copy of the MPL was not distributed with this file, you can obtain one at
// https://mozilla.org/MPL/2.0/.

/** The list's version, as it names itself. */
export const PUBLIC_SUFFIX_LIST_VERSION = ${JSON.stringify(version)};

export const PUBLIC_SUFFIX_RULES =
  ${JSON.stringify(rules)};
`,
  );
  console.log(`Wrote ${count} rules from version ${version} (${rules.length} characters) to ${OUT}.`);
  const listed = supplementNowListed(list);
  if (listed.length > 0) console.log(`The list now has ${listed.join(", ")}: remove them from packages/server/src/public-suffix-supplement.ts.`);
}
