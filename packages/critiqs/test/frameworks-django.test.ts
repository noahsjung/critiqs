function app(files: Record<string, string | null>) {
  const root = mkdtempSync(join(process.env.TMPDIR ?? tmpdir(), "critiqs-django-"));
  for (const [name, text] of Object.entries(files)) {
    if (text === null) continue;
    mkdirSync(dirname(join(root, name)), { recursive: true });
    writeFileSync(join(root, name), text);
  }
  return root;
}
const starter = (files: Record<string, string | null> = {}) =>
  app({ "manage.py": MANAGE, "mysite/__init__.py": "", "mysite/settings.py": SETTINGS, "templates/base.html": BASE, "templates/home.html": HOME, ...files });
const read = (root: string, name: string) => readFileSync(join(root, name), "utf8");
